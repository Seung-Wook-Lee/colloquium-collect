"""층(11/25 의장 새 유니버스): 번호 = '층-순번'(U0-1, K1-9 …). U = 미국 상장, K = 한국 상장.
분석 도구(국면 B08·주문 바구니·기준층 처리 등)는 아직 예전 묶음으로 돈다. 그래서 새 층을 그 묶음(S0~S6)으로 읽는 규칙을 여기 한 곳에 둔다.
층별로 다른 분석 도구를 쓰는 것은 의장 지시가 있을 때 이 규칙을 고친다.
  기준(S0): U0 지수·채권·현금·금·해외, K0 지수·현금·금·커버드콜
  AI(S1 미국 반도체, S2 한국 반도체, S3 빅테크): U1 → S1, K1 → S2, U2 → S3
  경기(S4): U3 산업재·에너지·소재, U7 경기소비·여행, K2 조선·방산·전력·원전, K3 자동차·2차전지·소재
  금융(S5): U4, K4
  방어(S6): U5 헬스케어, U6 필수소비·유틸리티·리츠, K5 소비·헬스케어·통신·지주"""
import pandas as pd

GROUP = {'U0': 'S0', 'K0': 'S0', 'U1': 'S1', 'K1': 'S2', 'U2': 'S3',
         'U3': 'S4', 'U7': 'S4', 'K2': 'S4', 'K3': 'S4', 'U4': 'S5', 'K4': 'S5', 'U5': 'S6', 'U6': 'S6', 'K5': 'S6'}


def layer_of(no):
    """번호(U1-4) → 층 코드(U1)."""
    return str(no).split('-')[0]


# 편출(의장 지시, 새 유니버스 파일을 만들지 않고 여기 코드 한 곳에서 뺌 — 11/26 의장 "새 파일 만들지 말라니까").
# 여기 있는 티커는 유니버스를 읽는 모든 곳(회의·엔진·블록 1·수집)에서 빠지고, 10년치 데이터베이스 칸도 다음 가격 수집 때 PS.keep이 지운다.
# 유니버스 관리(11/26 의장 "유니버스 관리하는 코드 만들어. 그걸 돌리면 자동으로 CSV에서 지워지도록 하고, 추가할 때는 추가되도록"):
#   빼기 = OUT, 넣기 = ADD(유니버스 한 줄과 같은 칸). 이 파일을 고쳐 main에 머지하면 universe.yml이 저절로 돌아
#   collect/universe_manage.py가 10년치 데이터베이스 유니버스 칸(1_data/가격10년_유니버스.csv.gz) 안에서 줄을 지우거나 더하고,
#   지운 종목은 가격·EPS 칸에서도 지움. 더한 종목의 과거 가격은 다음 수집이 새 종목만 받음(새 파일 없음).
OUT = {'466920.KS': '11/26 의장 "sol 조선 .. 유니버스에서 지워"(SOL 조선TOP3플러스)'}
OUT_NAME = {'466920.KS': 'SOL 조선TOP3플러스'}   # 편출 종목 이름(아침 수집 파일에 이름으로만 남은 줄도 지우려고)
ADD = []   # 예: {'번호': 'K2-11', '정식 종목명': '…', '시장': '한국', '구분': '개별주', '코드': '000000', 'yfinance 티커': '000000.KS', '편입일': '2026-11-26'}


def drop_out(u):
    """유니버스 표에서 편출 티커 줄을 뺌."""
    if 'yfinance 티커' not in u:
        return u
    return u[~u['yfinance 티커'].astype(str).isin(OUT)]


def apply(u):
    """유니버스 표에 분석 묶음을 '층' 칸으로 붙임(새 층 코드는 '층 코드' 칸). 옛 유니버스(S0~S6)는 그대로. 편출(OUT)은 뺌."""
    u = drop_out(u)
    if '번호' not in u or not u['번호'].astype(str).str.match(r'^[UK]\d-\d+$').any():
        return u
    u = u.copy()
    u['층 코드'] = u['번호'].astype(str).map(layer_of)
    u['층'] = u['층 코드'].map(GROUP).fillna(u.get('층', pd.Series('', index=u.index)))
    return u
